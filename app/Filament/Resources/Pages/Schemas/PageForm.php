<?php

declare(strict_types=1);

namespace App\Filament\Resources\Pages\Schemas;

use App\Filament\Forms\Components\SlugField;
use App\Filament\Forms\Components\SpatieMediaLibrary;
use App\Filament\Resources\Seo\Schemas\SeoForm;
use App\Support\Media\ImageMimeTypes;
use Filament\Forms\Components\RichEditor;
use Filament\Forms\Components\TextInput;
use Filament\Forms\Components\Toggle;
use Filament\Schemas\Components\Grid;
use Filament\Schemas\Components\Tabs;
use Filament\Schemas\Components\Tabs\Tab;
use Filament\Schemas\Schema;
use Spatie\Image\Enums\Fit;
use Spatie\Image\Image;

final class PageForm
{
    public static function configure(Schema $schema): Schema
    {
        return $schema
            ->components([
                Tabs::make('Целевая страница')
                    ->tabs([
                        Tab::make('Основное')
                            ->schema([
                                SpatieMediaLibrary::make('images')
                                    ->label('Изображения')
                                    ->panelLayout('grid')
                                    ->collection('images')
                                    ->multiple()
                                    ->reorderable()
                                    ->maxFiles(5)
                                    ->processImage(static fn (Image $image): Image => $image->fit(Fit::Crop, 1200, 800))
                                    ->helperText('Рекомендуемый размер: 1200×800 пикселей.')
                                    ->columnSpanFull(),
                                Grid::make(2)
                                    ->schema([
                                        TextInput::make('title')
                                            ->label('Заголовок')
                                            ->required()
                                            ->maxLength(200),
                                        ...SlugField::make(autoGenerated: false),
                                    ])
                                    ->columnSpanFull(),
                                RichEditor::make('content')
                                    ->label('Содержание')
                                    ->required()
                                    ->maxLength(50000)
                                    ->fileAttachmentsAcceptedFileTypes(ImageMimeTypes::ALLOWED)
                                    ->fileAttachmentsMaxSize(5120)
                                    ->preventFileAttachmentPathTampering()
                                    ->resizableImages()
                                    ->columnSpanFull(),
                                Toggle::make('is_active')
                                    ->label('Активна')
                                    ->columnSpanFull(),
                            ]),
                        Tab::make('SEO')
                            ->schema([
                                SeoForm::relationshipSection(),
                            ]),
                    ])
                    ->persistTabInQueryString()
                    ->columnSpanFull(),
            ]);
    }
}
