<?php

declare(strict_types=1);

namespace App\Filament\Resources\ProductAttributes\Schemas;

use App\Filament\Forms\Components\SlugField;
use App\Models\ProductAttribute;
use Filament\Forms\Components\TextInput;
use Filament\Schemas\Components\Grid;
use Filament\Schemas\Schema;

final class ProductAttributeForm
{
    public static function configure(Schema $schema): Schema
    {
        return $schema
            ->components([
                Grid::make(2)
                    ->schema([
                        TextInput::make('name')
                            ->label('Название')
                            ->required()
                            ->unique(ProductAttribute::class, 'name', ignoreRecord: true)
                            ->maxLength(255),
                        ...SlugField::make(autoGenerated: true),
                    ])
                    ->columnSpanFull(),
            ]);
    }
}
