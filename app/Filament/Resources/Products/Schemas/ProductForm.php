<?php

declare(strict_types=1);

namespace App\Filament\Resources\Products\Schemas;

use App\Enums\ProductUnit;
use App\Filament\Forms\Components\MediaImageUpload;
use App\Filament\Forms\Components\SlugField;
use App\Filament\Resources\Seo\Schemas\SeoForm;
use App\Models\Category;
use App\Models\ProductAttribute;
use App\Models\ProductVariant;
use App\Support\Values\Money;
use Closure;
use Filament\Forms\Components\Repeater;
use Filament\Forms\Components\Select;
use Filament\Forms\Components\Textarea;
use Filament\Forms\Components\TextInput;
use Filament\Forms\Components\Toggle;
use Filament\Schemas\Components\Flex;
use Filament\Schemas\Components\Grid;
use Filament\Schemas\Components\Tabs;
use Filament\Schemas\Components\Tabs\Tab;
use Filament\Schemas\Components\Utilities\Get;
use Filament\Schemas\Schema;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Spatie\Image\Enums\Fit;
use Spatie\Image\Image;

final class ProductForm
{
    public static function configure(Schema $schema): Schema
    {
        return $schema
            ->components([
                Tabs::make('Товар')
                    ->tabs([
                        Tab::make('Основное')
                            ->schema([
                                MediaImageUpload::make('image')
                                    ->label('Главное изображение')
                                    ->collection('image')
                                    ->required()
                                    ->maxFiles(1)
                                    ->processImage(static fn (Image $image): Image => $image->fit(Fit::Fill, 1200, 1200, backgroundColor: '#ffffff'))
                                    ->helperText('Рекомендуемый размер: 1200×1200 пикселей.'),
                                MediaImageUpload::make('gallery')
                                    ->label('Галерея')
                                    ->collection('gallery')
                                    ->multiple()
                                    ->reorderable()
                                    ->maxFiles(10)
                                    ->processImage(static fn (Image $image): Image => $image->fit(Fit::Fill, 1200, 1200, backgroundColor: '#ffffff'))
                                    ->helperText('Рекомендуемый размер: 1200×1200 пикселей.'),
                                Grid::make(2)
                                    ->schema([
                                        TextInput::make('name')
                                            ->label('Название')
                                            ->required()
                                            ->maxLength(255),
                                        ...SlugField::make(autoGenerated: true),
                                    ]),
                                Select::make('category_id')
                                    ->label('Категория')
                                    ->options(self::categoryOptions(...))
                                    ->disableOptionWhen(static fn (string $value): bool => in_array((int) $value, self::parentCategoryIds(), true))
                                    ->searchable()
                                    ->preload()
                                    ->required(),
                                Textarea::make('description')
                                    ->label('Описание')
                                    ->rows(8)
                                    ->columnSpanFull(),
                                Grid::make(3)
                                    ->schema([
                                        Toggle::make('is_new')
                                            ->label('Новинка'),
                                        Toggle::make('is_hit')
                                            ->label('Хит'),
                                        Toggle::make('is_active')
                                            ->label('Активен')
                                            ->rules([
                                                fn (Get $get): Closure => static function (string $attribute, mixed $value, Closure $fail) use ($get): void {
                                                    if (! $value) {
                                                        return;
                                                    }

                                                    $hasActiveVariant = collect($get('variants'))
                                                        ->contains(static fn (array $variant): bool => (bool) ($variant['is_active'] ?? false));

                                                    if (! $hasActiveVariant) {
                                                        $fail('Для публикации товара добавьте хотя бы один активный вариант.');
                                                    }
                                                },
                                            ]),
                                    ]),
                            ]),
                        Tab::make('Варианты')
                            ->schema([
                                Repeater::make('variants')
                                    ->label('Варианты товара')
                                    ->relationship()
                                    ->orderColumn('order')
                                    ->schema([
                                        Grid::make(3)
                                            ->schema([
                                                TextInput::make('sku')
                                                    ->label('Артикул')
                                                    ->required()
                                                    ->maxLength(255)
                                                    ->unique(ProductVariant::class, 'sku', ignoreRecord: true),
                                                TextInput::make('value')
                                                    ->label('Количество')
                                                    ->numeric()
                                                    ->minValue(0.001)
                                                    ->step(0.001)
                                                    ->required()
                                                    ->live(onBlur: true),
                                                Select::make('unit')
                                                    ->label('Единица')
                                                    ->options(ProductUnit::class)
                                                    ->required()
                                                    ->live(),
                                                TextInput::make('price')
                                                    ->label('Цена')
                                                    ->formatStateUsing(static fn (mixed $state): mixed => $state instanceof Money ? $state->toRubles() : $state)
                                                    ->integer()
                                                    ->minValue(1)
                                                    ->suffix('₽')
                                                    ->required()
                                                    ->live(onBlur: true),
                                                TextInput::make('discount_percent')
                                                    ->label('Скидка')
                                                    ->integer()
                                                    ->minValue(1)
                                                    ->maxValue(99)
                                                    ->suffix('%'),
                                                Flex::make([
                                                    Toggle::make('is_active')
                                                        ->label('Активен')
                                                        ->default(true)
                                                        ->grow(false),
                                                    Toggle::make('is_preorder')
                                                        ->label('Доступен по предзаказу')
                                                        ->grow(false),
                                                ])
                                                    ->columnSpanFull(),
                                            ]),
                                    ])
                                    ->itemLabel(self::variantLabel(...))
                                    ->defaultItems(1)
                                    ->minItems(1)
                                    ->cloneable()
                                    ->collapsible()
                                    ->addActionLabel('Добавить вариант')
                                    ->columnSpanFull(),
                            ]),
                        Tab::make('Характеристики')
                            ->schema([
                                Repeater::make('attributeValues')
                                    ->label('Характеристики товара')
                                    ->relationship()
                                    ->orderColumn('order')
                                    ->schema([
                                        Select::make('product_attribute_id')
                                            ->label('Характеристика')
                                            ->relationship('productAttribute', 'name', modifyQueryUsing: static fn (Builder $query): Builder => $query->orderBy('name'))
                                            ->searchable()
                                            ->preload()
                                            ->disableOptionsWhenSelectedInSiblingRepeaterItems()
                                            ->createOptionForm([
                                                TextInput::make('name')
                                                    ->label('Название')
                                                    ->required()
                                                    ->unique(ProductAttribute::class, 'name')
                                                    ->maxLength(255),
                                                ...SlugField::make(autoGenerated: true),
                                            ])
                                            ->createOptionModalHeading('Создать характеристику')
                                            ->required(),
                                        TextInput::make('value')
                                            ->label('Значение')
                                            ->required()
                                            ->maxLength(255),
                                    ])
                                    ->columns(2)
                                    ->collapsible()
                                    ->addActionLabel('Добавить характеристику')
                                    ->columnSpanFull(),
                            ]),
                        Tab::make('SEO')
                            ->schema([
                                SeoForm::relationshipSection(),
                            ]),
                    ])
                    ->persistTabInQueryString()
                    ->columnSpanFull(),
            ]);
    }

    private static function categoryOptions(): array
    {
        $options = [];
        $categories = Category::query()
            ->whereNull('parent_id')
            ->with(['children' => static fn (HasMany $query): HasMany => $query->orderBy('order')->orderBy('name')])
            ->orderBy('order')
            ->orderBy('name')
            ->get();

        foreach ($categories as $category) {
            $options[$category->getKey()] = $category->name;

            foreach ($category->children as $child) {
                $options[$child->getKey()] = '    ↳ '.$child->name;
            }
        }

        return $options;
    }

    private static function parentCategoryIds(): array
    {
        static $categoryIds;

        return $categoryIds ??= Category::query()
            ->whereHas('children')
            ->pluck('id')
            ->map(static fn (mixed $id): int => (int) $id)
            ->all();
    }

    private static function variantLabel(array $state): string
    {
        $value = filled($state['value'] ?? null)
            ? rtrim(rtrim(number_format((float) $state['value'], 3, '.', ''), '0'), '.')
            : null;
        $unitState = $state['unit'] ?? null;
        $unit = $unitState instanceof ProductUnit
            ? $unitState->getLabel()
            : ProductUnit::tryFrom(is_string($unitState) ? $unitState : '')?->getLabel();
        $priceState = $state['price'] ?? null;
        $money = match (true) {
            $priceState instanceof Money => $priceState,
            is_int($priceState), is_string($priceState) => Money::tryFromRubles($priceState),
            default => null,
        };
        $price = $money?->format();

        return collect([$value !== null && $unit !== null ? "{$value} {$unit}" : null, $price])
            ->filter()
            ->join(' · ') ?: 'Новый вариант';
    }
}
